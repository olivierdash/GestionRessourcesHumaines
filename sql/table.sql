
-- 1. TABLES DES UTILISATEURS ET RÔLES
-- =====================================================================
CREATE TABLE utilisateur (
    id_utilisateur  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_prenom      VARCHAR(255) NOT NULL,
    email           VARCHAR(255) UNIQUE NOT NULL,
    mot_de_passe    VARCHAR(255) NOT NULL, -- hashé par Spring Security (BCrypt)
    role            VARCHAR(50)  NOT NULL  -- 'MANAGER', 'RH', 'FINANCE', 'DG'
);

CREATE TABLE departement (
    id_departement  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre           VARCHAR(255) NOT NULL,
    id_manager      INTEGER NULL,
    CONSTRAINT fk_departement_manager
        FOREIGN KEY (id_manager) REFERENCES utilisateur(id_utilisateur)
);

CREATE TABLE candidat (
    id_candidat  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom          VARCHAR(255) NOT NULL,
    prenom       VARCHAR(255) NOT NULL,
    telephone    VARCHAR(20),
    email        VARCHAR(255) UNIQUE NOT NULL,
    cv_url       VARCHAR(500)
);

CREATE TABLE etat_demande (
    id_etat_demande  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intitule         VARCHAR(100) NOT NULL -- 'BROUILLON', 'VALIDE_RH', 'VALIDE_FINANCE', 'VALIDE_DG'
);

-- 2. STRUCTURE DE L'ENTREPRISE
-- =====================================================================
CREATE TABLE poste (
    id_poste         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departement   INTEGER NOT NULL,
    date_effet       DATE,
    intitule         VARCHAR(255) NOT NULL,
    lieu             VARCHAR(255),
    duree_hebdo      INTEGER,
    CONSTRAINT fk_poste_departement
        FOREIGN KEY (id_departement) REFERENCES departement(id_departement)
);

CREATE TABLE poste_mission (
    id_mission  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_poste    INTEGER NOT NULL,
    titre       VARCHAR(255) NOT NULL,
    CONSTRAINT fk_poste_mission_poste
        FOREIGN KEY (id_poste) REFERENCES poste(id_poste)
);

CREATE TABLE grille_salarial (
    id_grille       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_poste        INTEGER NOT NULL,
    id_departement  INTEGER NOT NULL,
    salaire_min     NUMERIC(10,2) NOT NULL,
    salaire_max     NUMERIC(10,2) NOT NULL,
    salaire_moyen   NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_grille_poste
        FOREIGN KEY (id_poste) REFERENCES poste(id_poste),
    CONSTRAINT fk_grille_departement
        FOREIGN KEY (id_departement) REFERENCES departement(id_departement)
);

-- 3. BLOC 1 : DEMANDE ET WORKFLOW
-- =====================================================================
CREATE TABLE demande_recrutement (
    id_demande_recrutement  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_manager              INTEGER NOT NULL,
    id_poste                INTEGER NOT NULL,
    date_creation           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    effectif                INTEGER NOT NULL,
    motif                   TEXT,
    CONSTRAINT fk_demande_manager
        FOREIGN KEY (id_manager) REFERENCES utilisateur(id_utilisateur),
    CONSTRAINT fk_demande_poste
        FOREIGN KEY (id_poste) REFERENCES poste(id_poste)
);

CREATE TABLE historique_demande_recrutement (
    id_historique_demande_recrutement  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demande_recrutement             INTEGER NOT NULL,
    id_etat_demande                    INTEGER NOT NULL,
    id_validateur                      INTEGER NOT NULL,
    date_changement                    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_hist_demande
        FOREIGN KEY (id_demande_recrutement) REFERENCES demande_recrutement(id_demande_recrutement),
    CONSTRAINT fk_hist_etat
        FOREIGN KEY (id_etat_demande) REFERENCES etat_demande(id_etat_demande),
    CONSTRAINT fk_hist_validateur
        FOREIGN KEY (id_validateur) REFERENCES utilisateur(id_utilisateur)
);

-- 4. BLOC 2 & 3 : RECRUTEMENT ET PROPOSITION
-- =====================================================================
CREATE TABLE candidature (
    id_candidature             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidat                INTEGER NOT NULL,
    id_demande_recrutement     INTEGER NOT NULL,
    date_depot_candidature     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    statut_candidature         VARCHAR(50) NOT NULL,
    CONSTRAINT fk_candidature_candidat
        FOREIGN KEY (id_candidat) REFERENCES candidat(id_candidat),
    CONSTRAINT fk_candidature_demande
        FOREIGN KEY (id_demande_recrutement) REFERENCES demande_recrutement(id_demande_recrutement)
);

CREATE TABLE evaluation (
    id_evaluation    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature   INTEGER NOT NULL,
    evaluation       VARCHAR(255),
    note             NUMERIC(5,2),
    date_evaluation  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evaluation_candidature
        FOREIGN KEY (id_candidature) REFERENCES candidature(id_candidature)
);

CREATE TABLE proposition_embauche (
    id_proposition     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature     INTEGER NOT NULL,
    salaire_propose    NUMERIC(10,2) NOT NULL,
    salaire_final      NUMERIC(10,2),
    date_proposition   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    date_expiration    TIMESTAMP NOT NULL,
    statut_proposition VARCHAR(50) NOT NULL,
    date_decision      TIMESTAMP,
    CONSTRAINT fk_proposition_candidature
        FOREIGN KEY (id_candidature) REFERENCES candidature(id_candidature)
);

CREATE TABLE validation_proposition (
    id_validation_proposition   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proposition              INTEGER NOT NULL,
    id_validateur               INTEGER NOT NULL,
    departement_role            VARCHAR(100),
    decision                    VARCHAR(50) NOT NULL,
    date_validation_proposition TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    commentaire                 TEXT,
    CONSTRAINT fk_val_prop_proposition
        FOREIGN KEY (id_proposition) REFERENCES proposition_embauche(id_proposition),
    CONSTRAINT fk_val_prop_validateur
        FOREIGN KEY (id_validateur) REFERENCES utilisateur(id_utilisateur)
);

-- 5. BLOC 3 & 4 : EMBAUCHE ET CONTRAT
-- =====================================================================
CREATE TABLE employer (
    id_employer      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature   INTEGER UNIQUE NOT NULL,
    matricule        VARCHAR(50) UNIQUE NOT NULL,
    hiring_date      DATE NOT NULL,
    status_employer  VARCHAR(50) NOT NULL,
    CONSTRAINT fk_employer_candidature
        FOREIGN KEY (id_candidature) REFERENCES candidature(id_candidature)
);

CREATE TABLE contract (
    id_contract     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employer     INTEGER NOT NULL,
    id_poste        INTEGER NOT NULL,
    type_contrat    VARCHAR(50) NOT NULL,
    date_debut      DATE NOT NULL,
    date_fin        DATE,
    salaire_mensuel NUMERIC(10,2) NOT NULL,
    status          VARCHAR(50) NOT NULL,
    CONSTRAINT fk_contract_employer
        FOREIGN KEY (id_employer) REFERENCES employer(id_employer),
    CONSTRAINT fk_contract_poste
        FOREIGN KEY (id_poste) REFERENCES poste(id_poste)
);

-- 6. NOTIFICATIONS
-- =====================================================================
CREATE TABLE notification (
    id_notification              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_destinataire_candidat     INTEGER NULL,
    id_destinataire_utilisateur  INTEGER NULL,
    type_notification            VARCHAR(50) NOT NULL,
    message                      VARCHAR(255) NOT NULL,
    lien_action                  VARCHAR(255),
    est_lu                       BOOLEAN DEFAULT FALSE,
    date_creation                TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notif_candidat
        FOREIGN KEY (id_destinataire_candidat) REFERENCES candidat(id_candidat),
    CONSTRAINT fk_notif_utilisateur
        FOREIGN KEY (id_destinataire_utilisateur) REFERENCES utilisateur(id_utilisateur),
    -- (optionnel) au moins une des deux cibles doit être renseignée
    CONSTRAINT chk_notif_destinataire
        CHECK (id_destinataire_candidat IS NOT NULL OR id_destinataire_utilisateur IS NOT NULL)
);

-- =====================================================================
-- INDEX sur les clés étrangères (PostgreSQL ne les crée pas automatiquement)
-- =====================================================================
CREATE INDEX idx_departement_manager            ON departement(id_manager);
CREATE INDEX idx_poste_departement              ON poste(id_departement);
CREATE INDEX idx_poste_mission_poste            ON poste_mission(id_poste);
CREATE INDEX idx_grille_poste                   ON grille_salarial(id_poste);
CREATE INDEX idx_grille_departement             ON grille_salarial(id_departement);
CREATE INDEX idx_demande_manager                ON demande_recrutement(id_manager);
CREATE INDEX idx_demande_poste                  ON demande_recrutement(id_poste);
CREATE INDEX idx_hist_demande                   ON historique_demande_recrutement(id_demande_recrutement);
CREATE INDEX idx_hist_etat                      ON historique_demande_recrutement(id_etat_demande);
CREATE INDEX idx_hist_validateur                ON historique_demande_recrutement(id_validateur);
CREATE INDEX idx_candidature_candidat           ON candidature(id_candidat);
CREATE INDEX idx_candidature_demande            ON candidature(id_demande_recrutement);
CREATE INDEX idx_evaluation_candidature         ON evaluation(id_candidature);
CREATE INDEX idx_proposition_candidature        ON proposition_embauche(id_candidature);
CREATE INDEX idx_val_prop_proposition           ON validation_proposition(id_proposition);
CREATE INDEX idx_val_prop_validateur            ON validation_proposition(id_validateur);
CREATE INDEX idx_employer_candidature           ON employer(id_candidature);
CREATE INDEX idx_contract_employer              ON contract(id_employer);
CREATE INDEX idx_contract_poste                 ON contract(id_poste);
CREATE INDEX idx_notif_candidat                 ON notification(id_destinataire_candidat);
CREATE INDEX idx_notif_utilisateur              ON notification(id_destinataire_utilisateur);